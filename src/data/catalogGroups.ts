export type CatalogGroup = {
  id: string;
  title: string;
  description: string;
  imageKey: string;
  items: readonly string[];
};

function materialRange(start: string, end: string) {
  const first = MATERIAL_SUBCATEGORIES.indexOf(
    start as (typeof MATERIAL_SUBCATEGORIES)[number]
  );
  const last = MATERIAL_SUBCATEGORIES.indexOf(
    end as (typeof MATERIAL_SUBCATEGORIES)[number]
  );

  if (first < 0 || last < first) return [];
  return MATERIAL_SUBCATEGORIES.slice(first, last + 1);
}

